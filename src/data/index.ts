/** 姓名组合 —— 用于确定性生成人物名 */
export function formatPersonName(rng: { pick<T>(items: readonly T[]): T }, index: number): string {
  const first = PERSON_FIRST_NAMES[index % PERSON_FIRST_NAMES.length]!;
  const last = PERSON_LAST_NAMES[Math.floor(index / PERSON_FIRST_NAMES.length) % PERSON_LAST_NAMES.length]!;
  // 少量随机性, 避免所有人都叫"阿德里·冯·艾森巴赫"
  if (rng.pick([0, 0, 0, 1, 1]) === 1) {
    return `${first}${last}`;
  }
  return `${first}${last}`;
}

